CREATE TABLE IF NOT EXISTS identity_verification_attempts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL,
    document_type VARCHAR(50) NOT NULL DEFAULT 'national_id',
    status VARCHAR(50) NOT NULL DEFAULT 'uploaded',
    decision_status VARCHAR(50) NOT NULL DEFAULT 'manual_review',
    decision_score INT NOT NULL DEFAULT 0,
    failure_reason TEXT NULL,
    original_image_path VARCHAR(255) NULL,
    processed_image_path VARCHAR(255) NULL,
    original_filename VARCHAR(255) NULL,
    mime_type VARCHAR(100) NULL,
    file_size BIGINT NULL,
    image_width INT NULL,
    image_height INT NULL,
    brightness_score DECIMAL(8,2) NULL,
    blur_score DECIMAL(8,2) NULL,
    ocr_status VARCHAR(50) NULL,
    ocr_message TEXT NULL,
    ocr_raw_text LONGTEXT NULL,
    extracted_fields JSON NULL,
    decision_checks JSON NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_identity_verification_attempts_user_id (user_id),
    INDEX idx_identity_verification_attempts_status (status),
    INDEX idx_identity_verification_attempts_decision_status (decision_status),
    CONSTRAINT fk_identity_verification_attempts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
